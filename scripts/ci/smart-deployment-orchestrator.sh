#!/bin/bash
#
# Smart Deployment Orchestrator
# Implements test-driven deployment with alignment loops
# Automated discovery -> test -> align -> test cycle until deployment ready
#

set -e

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
PURPLE='\033[0;35m'
CYAN='\033[0;36m'
NC='\033[0m'

# Configuration
MAX_ALIGNMENT_ATTEMPTS=3
REPORT_EMAIL="${DEPLOYMENT_REPORT_EMAIL:-}" # Set via environment
REPORT_WEBHOOK="${DEPLOYMENT_REPORT_WEBHOOK:-}" # Set via environment
REPORT_DIR="deployment-reports"

echo -e "${CYAN}"
cat << "EOF"
╔══════════════════════════════════════════════════════════╗
║          🚀 SMART DEPLOYMENT ORCHESTRATOR 🚀            ║
║               Test-Driven Deployment                     ║
║        Discovery → Test → Align → Deploy                ║
╚══════════════════════════════════════════════════════════╝
EOF
echo -e "${NC}"

# Create report directory
mkdir -p "$REPORT_DIR"
REPORT_FILE="$REPORT_DIR/deployment-report-$(date +%Y%m%d-%H%M%S).md"

# Initialize report
cat > "$REPORT_FILE" << EOF
# MEVana Deployment Report

**Date**: $(date)
**Server**: $(hostname) ($(hostname -I | awk '{print $1}'))
**Working Directory**: $(pwd)

## Executive Summary

EOF

log_to_report() {
    local message="$1"
    echo "$message" >> "$REPORT_FILE"
    echo -e "$message"
}

log_phase() {
    local phase="$1"
    local message="$2"
    log_to_report ""
    log_to_report "## $phase"
    log_to_report ""
    log_to_report "$message"
    echo -e "${PURPLE}🔄 PHASE: $phase${NC}"
    echo -e "${BLUE}$message${NC}"
}

log_result() {
    local status="$1"
    local message="$2"
    case "$status" in
        "PASS")
            log_to_report "✅ **PASS**: $message"
            echo -e "${GREEN}✅ PASS: $message${NC}"
            ;;
        "FAIL")
            log_to_report "❌ **FAIL**: $message"
            echo -e "${RED}❌ FAIL: $message${NC}"
            ;;
        "WARN")
            log_to_report "⚠️ **WARN**: $message"
            echo -e "${YELLOW}⚠️ WARN: $message${NC}"
            ;;
        "INFO")
            log_to_report "ℹ️ **INFO**: $message"
            echo -e "${BLUE}ℹ️ INFO: $message${NC}"
            ;;
    esac
}

# Send report function
send_report() {
    local status="$1"
    local summary="$2"

    # Add summary to report
    cat >> "$REPORT_FILE" << EOF

## Final Status: $status

$summary

---
*Generated by MEVana Smart Deployment Orchestrator*
*Report time: $(date)*
EOF

    echo -e "${BLUE}📊 Report saved: $REPORT_FILE${NC}"

    # GitHub notification (QUICKEST - no setup needed!)
    if [ -f "scripts/ci/github-deployment-notifier.sh" ]; then
        echo -e "${BLUE}🐙 Creating GitHub notification...${NC}"
        ./scripts/ci/github-deployment-notifier.sh "$REPORT_FILE" "$status" "$summary"
    fi

    # Email report if configured
    if [ -n "$REPORT_EMAIL" ] && command -v mail >/dev/null 2>&1; then
        subject="MEVana Deployment Report - $status"
        cat "$REPORT_FILE" | mail -s "$subject" "$REPORT_EMAIL"
        echo -e "${GREEN}📧 Report emailed to: $REPORT_EMAIL${NC}"
    fi

    # Webhook report if configured
    if [ -n "$REPORT_WEBHOOK" ] && command -v curl >/dev/null 2>&1; then
        webhook_payload=$(cat << WEBHOOK_EOF
{
    "text": "MEVana Deployment Report - $status",
    "attachments": [
        {
            "color": "$( [ "$status" = "SUCCESS" ] && echo "good" || echo "danger" )",
            "title": "Deployment Status: $status",
            "text": "$summary",
            "footer": "MEVana Smart Deployment Orchestrator",
            "ts": $(date +%s)
        }
    ]
}
WEBHOOK_EOF
)
        curl -X POST -H 'Content-type: application/json' \
             --data "$webhook_payload" \
             "$REPORT_WEBHOOK" >/dev/null 2>&1
        echo -e "${GREEN}🔗 Report sent to webhook${NC}"
    fi
}

# =============================================================================
# PHASE 1: DISCOVERY
# =============================================================================

log_phase "Phase 1: Discovery" "Comprehensive infrastructure analysis"

if [ ! -f "scripts/ci/comprehensive-infrastructure-discovery.sh" ]; then
    log_result "FAIL" "Discovery script not found"
    send_report "ERROR" "Discovery script missing - cannot proceed"
    exit 1
fi

log_result "INFO" "Running comprehensive infrastructure discovery..."

# Run discovery and capture output
DISCOVERY_OUTPUT=$(./scripts/ci/comprehensive-infrastructure-discovery.sh 2>&1)
DISCOVERY_EXIT_CODE=$?

# Log discovery results to report
log_to_report "### Discovery Results"
log_to_report ""
log_to_report '```'
log_to_report "$DISCOVERY_OUTPUT"
log_to_report '```'

if [ $DISCOVERY_EXIT_CODE -eq 0 ]; then
    log_result "PASS" "Discovery completed successfully"
else
    log_result "WARN" "Discovery completed with warnings (exit code: $DISCOVERY_EXIT_CODE)"
fi

# =============================================================================
# PHASE 2: ALIGNMENT LOOP
# =============================================================================

ALIGNMENT_ATTEMPT=1
DEPLOYMENT_READY=false

while [ $ALIGNMENT_ATTEMPT -le $MAX_ALIGNMENT_ATTEMPTS ] && [ "$DEPLOYMENT_READY" = false ]; do
    log_phase "Phase 2.$ALIGNMENT_ATTEMPT: Readiness Testing" "Testing deployment readiness (attempt $ALIGNMENT_ATTEMPT/$MAX_ALIGNMENT_ATTEMPTS)"

    # Run readiness test
    if [ ! -f "scripts/ci/deployment-readiness-test.sh" ]; then
        log_result "FAIL" "Readiness test script not found"
        send_report "ERROR" "Readiness test script missing - cannot proceed"
        exit 1
    fi

    log_result "INFO" "Running deployment readiness tests..."

    # Run readiness test and capture results
    READINESS_OUTPUT=$(./scripts/ci/deployment-readiness-test.sh 2>&1)
    READINESS_EXIT_CODE=$?

    # Log readiness results
    log_to_report "### Readiness Test Results (Attempt $ALIGNMENT_ATTEMPT)"
    log_to_report ""
    log_to_report '```'
    log_to_report "$READINESS_OUTPUT"
    log_to_report '```'

    case $READINESS_EXIT_CODE in
        0)
            log_result "PASS" "All readiness tests passed - deployment ready!"
            DEPLOYMENT_READY=true
            ;;
        1)
            log_result "FAIL" "Critical readiness issues found - alignment required"
            ;;
        2)
            log_result "WARN" "Most tests passed - deployment possible but risky"
            # Ask user or decide based on policy
            if [ "$ALLOW_RISKY_DEPLOYMENT" = "true" ]; then
                log_result "INFO" "Proceeding with risky deployment (ALLOW_RISKY_DEPLOYMENT=true)"
                DEPLOYMENT_READY=true
            else
                log_result "INFO" "Alignment recommended for safer deployment"
            fi
            ;;
        *)
            log_result "FAIL" "Readiness test failed unexpectedly (exit code: $READINESS_EXIT_CODE)"
            ;;
    esac

    if [ "$DEPLOYMENT_READY" = true ]; then
        log_result "PASS" "Readiness loop completed - proceeding to deployment"
        break
    fi

    # If not ready and we have attempts left, try alignment
    if [ $ALIGNMENT_ATTEMPT -lt $MAX_ALIGNMENT_ATTEMPTS ]; then
        log_phase "Phase 2.$ALIGNMENT_ATTEMPT: Alignment" "Attempting to fix alignment issues"

        # Attempt automatic alignment
        log_result "INFO" "Attempting automatic alignment fixes..."

        # Fix 1: Ensure Docker network
        if ! docker network ls | grep -q mevana_net; then
            log_result "INFO" "Creating mevana_net Docker network..."
            docker network create mevana_net 2>/dev/null || true
        fi

        # Fix 2: Check for configuration files and suggest fixes
        if [ ! -f "infrastructure/grafana/dashboards/curated/mevana-system-status.json" ]; then
            log_result "WARN" "Working dashboard missing - manual sync required"
            log_to_report "**Manual Action Required**: Copy working dashboard from local development"
        fi

        # Fix 3: Restart monitoring stack if containers exist but not accessible
        if docker ps -q -f name=grafana | grep -q .; then
            if ! curl -s --connect-timeout 3 http://localhost:3000/api/health >/dev/null 2>&1; then
                log_result "INFO" "Restarting Grafana container..."
                docker restart $(docker ps -q -f name=grafana) 2>/dev/null || true
                sleep 5
            fi
        fi

        if docker ps -q -f name=prometheus | grep -q .; then
            if ! curl -s --connect-timeout 3 http://localhost:9090/-/healthy >/dev/null 2>&1; then
                log_result "INFO" "Restarting Prometheus container..."
                docker restart $(docker ps -q -f name=prometheus) 2>/dev/null || true
                sleep 5
            fi
        fi

        log_result "INFO" "Alignment attempt completed"
    fi

    ((ALIGNMENT_ATTEMPT++))
done

# =============================================================================
# PHASE 3: DEPLOYMENT OR FAILURE
# =============================================================================

if [ "$DEPLOYMENT_READY" = true ]; then
    log_phase "Phase 3: Deployment" "Proceeding with actual deployment"

    # Deployment options
    DEPLOYMENT_METHOD="${DEPLOYMENT_METHOD:-github-actions}"

    case "$DEPLOYMENT_METHOD" in
        "github-actions")
            log_result "INFO" "Deployment method: GitHub Actions workflow"
            log_to_report "**Deployment Trigger**: Use GitHub Actions workflow 'self-hosted-deploy.yml'"
            log_to_report "**Next Steps**:"
            log_to_report "1. Trigger GitHub Actions workflow: self-hosted-deploy.yml"
            log_to_report "2. Monitor deployment progress in GitHub Actions"
            log_to_report "3. Run post-deployment validation"
            ;;
        "direct")
            log_result "INFO" "Deployment method: Direct deployment"
            if [ -f "scripts/rapid_deploy.sh" ]; then
                log_result "INFO" "Running direct deployment..."
                ./scripts/rapid_deploy.sh 2>&1 | tee -a "$REPORT_FILE"
            else
                log_result "FAIL" "Direct deployment script not found"
            fi
            ;;
        *)
            log_result "WARN" "Unknown deployment method: $DEPLOYMENT_METHOD"
            ;;
    esac

    send_report "SUCCESS" "Deployment orchestration completed successfully. All readiness tests passed after $((ALIGNMENT_ATTEMPT-1)) alignment attempts."
    exit 0

else
    log_phase "Phase 3: Deployment Blocked" "Maximum alignment attempts exceeded"

    log_result "FAIL" "Could not achieve deployment readiness after $MAX_ALIGNMENT_ATTEMPTS attempts"
    log_to_report "**Manual Intervention Required**:"
    log_to_report "1. Review alignment issues in readiness test output above"
    log_to_report "2. Manually fix critical configuration mismatches"
    log_to_report "3. Re-run orchestrator: ./scripts/ci/smart-deployment-orchestrator.sh"

    send_report "BLOCKED" "Deployment blocked due to persistent alignment issues. Manual intervention required."
    exit 1
fi