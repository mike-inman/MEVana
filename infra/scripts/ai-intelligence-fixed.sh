#!/usr/bin/env bash
set -euo pipefail

# Get repo metadata
REPO_OWNER="${1:-$(git config --get remote.origin.url | sed -n 's/.*[:\/]\(.*\)\/.*\.git/\1/p')}"
REPO_NAME="${2:-$(basename -s .git "$(git rev-parse --show-toplevel)")}"
BRANCH="${3:-$(git rev-parse --abbrev-ref HEAD)}"
TIMESTAMP=$(date -u "+%Y-%m-%d %H:%M UTC")

# Cross-platform "next analysis" date for macOS (BSD) and Linux (GNU)
if date -d '+1 day' '+%Y-%m-%d %H:%M UTC' >/dev/null 2>&1; then
  NEXT_ANALYSIS=$(date -d '+1 day' -u '+%Y-%m-%d %H:%M UTC')
else
  NEXT_ANALYSIS=$(date -v+1d -u '+%Y-%m-%d %H:%M UTC')
fi

COMMIT_SHA=$(git rev-parse HEAD)
TRIGGER="${GITHUB_EVENT_NAME:-manual}"
INTELLIGENCE_VERSION="2.0"

mkdir -p docs/intelligence/metrics docs/intelligence/analysis docs/intelligence/history

# 1. Generate ai_summary.json
cat > docs/intelligence/ai_summary.json <<EOL
{
  "project_intelligence": {
    "timestamp": "$TIMESTAMP",
    "commit_sha": "$COMMIT_SHA",
    "branch": "$BRANCH",
    "trigger": "$TRIGGER",
    "repository": "$REPO_OWNER/$REPO_NAME",
    "analysis_depth": "full",
    "intelligence_version": "$INTELLIGENCE_VERSION",
    "next_analysis": "$NEXT_ANALYSIS"
  },
  "current_state": {
    "overall_progress": 42,
    "key_blockers": ["Obtain Shyft gRPC credentials"],
    "active_agents": ["pattern-scout", "risk-guardian"],
    "recent_commits": [
      "$(git log -1 --pretty=format:'%ad: %s' --date=short)"
    ]
  },
  "vision": {
    "long_term": "Self-evolving, AI-powered crypto trading system",
    "success_metrics": [
      "Profitable strategies",
      "Real-time swap processing",
      "Agent collaboration"
    ]
  }
}
EOL

# 2. Generate insights.json (blockers, recommendations)
cat > docs/intelligence/insights.json <<EOL
{
  "insights": {
    "immediate_actions": [
      "Test Shyft gRPC client with valid credentials",
      "Complete Kafka producer implementation",
      "Add error handling and retry logic"
    ],
    "architecture_decisions": [
      "Choose AI agent communication protocol",
      "Design strategy coordination mechanisms",
      "Plan data storage for ML training"
    ],
    "performance_optimizations": [
      "Implement connection pooling for Redis",
      "Add Kafka consumer group balancing",
      "Create monitoring dashboards"
    ],
    "risk_mitigation": [
      "Add circuit breakers for external APIs",
      "Implement graceful degradation",
      "Create backup data sources"
    ]
  }
}
EOL

# 3. Generate dashboard.md (executive summary)
cat > docs/intelligence/dashboard.md <<EOL
# 🚀 Solana AI Trading Platform - Intelligence Dashboard

**Last Updated:** $TIMESTAMP  
**Branch:** $BRANCH  
**Commit:** $COMMIT_SHA

## 📊 Project State
- Progress: 42%
- Blockers: Obtain Shyft gRPC credentials

## 👥 Active Agents
- pattern-scout
- risk-guardian

## 🎯 Vision
Self-evolving, AI-powered crypto trading system.

## 📅 Recent Commit
- $(git log -1 --pretty=format:'%ad: %s' --date=short)

## ℹ️ Quick Links
- [AI Summary JSON](./ai_summary.json)
- [Insights](./insights.json)
- [Metrics](./metrics/)
- [Analysis](./analysis/)
EOL

# 4. Generate metrics/complexity.txt
RUST_LINES=$(find . -name "*.rs" -type f | xargs wc -l | tail -1 | awk '{print $1}')
DEPENDENCY_COUNT=$(find . -name "Cargo.toml" -exec grep -c "dependencies" {} \; | awk '{sum+=$1} END {print sum}')
cat > docs/intelligence/metrics/complexity.txt <<EOL
rust_lines_of_code: $RUST_LINES
total_dependencies: $DEPENDENCY_COUNT
EOL

# 5. Generate analysis/trends.json
cat > docs/intelligence/analysis/trends.json <<EOL
{
  "trends": {
    "code_growth": "increasing",
    "complexity": "manageable",
    "progress_velocity": "steady",
    "last_analysis": "$TIMESTAMP"
  }
}
EOL

# 6. Generate project_state_doc.md (human readable)
cat > docs/project_state_doc.md <<EOL
# Project State Report

**Last Updated:** $TIMESTAMP  
**Branch:** $BRANCH  
**Commit:** $COMMIT_SHA

## Progress
- 42% overall progress

## Blockers
- Obtain Shyft gRPC credentials

## Active Agents
- pattern-scout
- risk-guardian

## Recent Commit
- $(git log -1 --pretty=format:'%ad: %s' --date=short)

## Vision
Self-evolving, AI-powered crypto trading system.

---
_Auto-generated by ai-intelligence.sh_
EOL
```
